"""Write the data the frame's firmware carries built in.

    python -m painter firmware-data

writes firmware/painting_frame/generated.h with:

  STANDARD_SCENE   the standard rules (painting/scene.yaml, compiled like
                   publish does) used for paintings uploaded from the settings
                   page; layers that weren't uploaded are skipped
  STANDARD_LAYERS  the same layers as JSON, so the settings page knows which
                   PNG names to expect and what .wpl file each becomes
  DEMO_CASES       every season x weather combination (combos.py) for demo mode

and firmware/painting_frame/settings_page.h with the settings page
(web/settings.html).

Run it again after changing painting/scene.yaml, combos.py or the
settings page, then rebuild the firmware.
"""

from __future__ import annotations

import json
from pathlib import Path

from .combos import combos
from .publish import compile_scene, verify, wpl_name
from .scene import Scene

STANDARD = "painting"
FIRMWARE = Path("firmware/painting_frame")
OUT = FIRMWARE / "generated.h"
PAGE = FIRMWARE / "web" / "settings.html"
PAGE_OUT = FIRMWARE / "settings_page.h"


def _c_string(name: str, text: str) -> str:
    # raw string literal; the delimiter can't appear in our data
    assert ")WP\"" not in text
    return f'static const char {name}[] = R"WP({text})WP";\n'


def standard_layers(scene: Scene) -> list[dict]:
    out = []
    for layer in scene.spec.get("layers", []):
        reveal = layer.get("reveal")
        pngs = [s["file"] for s in layer.get("stages", [])] or [layer["file"]]
        out.append({
            "id": layer["id"],
            "required": not layer.get("optional", False),
            "files": [{"png": Path(p).name, "reveal": Path(reveal).name if reveal else None,
                       "wpl": wpl_name(p, reveal)} for p in pngs],
        })
    return out


def demo_text() -> str:
    lines = []
    cases = combos()
    lines.append(f"WPD2 {len(cases)}")
    for _, title, state in cases:
        lines.append(f"demo {title}")
        for k, v in state.items():
            lines.append(f"v {k} s {v}" if isinstance(v, str) else f"v {k} n {float(v):g}")
        lines.append("end")
    return "\n".join(lines) + "\n"


def write(cfg: dict) -> Path:
    root = Path(cfg["_root"])
    scene = Scene(root / STANDARD)
    disp = cfg.get("display", {})
    lines, _, compiled = compile_scene(scene, disp, rules_only=True)
    # there are no files to render, so only the rules themselves are checked
    problems = verify(scene, compiled, [(name, state) for name, _, state in combos()], decisions=False)
    if problems:
        raise SystemExit(f"{problems} problem(s) in the standard rules; nothing written")
    rotate = int(disp.get("rotate", 0)) % 360
    body = ("// Generated by `python -m painter firmware-data`; don't edit by hand.\n"
            "#pragma once\n\n"
            f"#define CANVAS_W {scene.width}\n#define CANVAS_H {scene.height}\n"
            f"#define CANVAS_ROTATE {rotate}\n\n"
            + _c_string("STANDARD_SCENE", "\n".join(lines) + "\n")
            + _c_string("STANDARD_LAYERS", json.dumps(standard_layers(scene)))
            + _c_string("DEMO_CASES", demo_text()))
    out = root / OUT
    out.write_text(body)
    print(f"wrote {OUT} ({out.stat().st_size / 1024:.0f} KB): {len(compiled)} standard layers, "
          f"{len(combos())} demo cases")
    page = (root / PAGE).read_text()
    (root / PAGE_OUT).write_text("// Generated from web/settings.html by `python -m painter firmware-data`.\n"
                                 "#pragma once\n\n" + _c_string("SETTINGS_PAGE", page))
    print(f"wrote {PAGE_OUT} ({len(page.encode()) / 1024:.0f} KB)")
    return out
